// Package feeds provides air-gap-ready and optional live-HTTP sovereign regulatory
// crosswalk, CISA KEV vulnerability, MITRE ATT&CK v16 technique, and regulatory
// lifecycle intelligence feeds with cryptographic SHA-256 sync receipts.
package feeds

import "github.com/mchorfa/xoscal/server/internal/ontology"

// CrosswalkEntry defines an authoritative cross-framework or multi-jurisdiction control mapping.
type CrosswalkEntry struct {
	CanonicalControl  string            `json:"canonical_control"`
	Title             string            `json:"title"`
	ThematicDomain    string            `json:"thematic_domain"`
	SP800171Controls  []string          `json:"sp800_171_controls"`
	ITSP10171Controls []string          `json:"itsp10171_controls"`
	CyberSecureCanada []string          `json:"cybersecure_canada"`
	NISTCSF2Subcats   []string          `json:"nist_csf2_subcats"`
	ISO27001Controls  []string          `json:"iso27001_controls"`
	BSIModules        []string          `json:"bsi_modules"`
	ANSSIRules        []string          `json:"anssi_rules"`
	NIS2Articles      []string          `json:"nis2_articles"`
	DORAPillars       []string          `json:"dora_pillars"`
	UKCyberEssentials []string          `json:"uk_cyber_essentials"`
	FrameworkControls map[string]string `json:"framework_controls,omitempty"`
}

// KEVAdvisoryEntry represents a real CISA Known Exploited Vulnerability (KEV) advisory
// linked to CWE weaknesses, MITRE ATT&CK techniques, and impacted/mitigating controls.
type KEVAdvisoryEntry struct {
	CVEID              string   `json:"cve_id"`
	Vendor             string   `json:"vendor"`
	Product            string   `json:"product"`
	VulnerabilityName  string   `json:"vulnerability_name"`
	DateAdded          string   `json:"date_added"`
	DueDate            string   `json:"due_date"`
	RansomwareUse      string   `json:"known_ransomware_campaign_use"`
	CWEID              string   `json:"cwe_id"`
	CWEName            string   `json:"cwe_name"`
	AttackTechniques   []string `json:"attack_techniques"`
	AttackedControls   []string `json:"attacked_controls"`
	MitigatingControls []string `json:"mitigating_controls"`
	ShortDescription   string   `json:"short_description"`
	Notes              string   `json:"notes,omitempty"`
}

// ThreatAdvisory aliases KEVAdvisoryEntry for active threat advisory consumers.
type ThreatAdvisory = KEVAdvisoryEntry

// AttackTechniqueEntry represents a MITRE ATT&CK v16 Enterprise technique and its
// mitigating NIST 800-53 Rev 5 / CCCS ITSP.10.033 controls.
type AttackTechniqueEntry struct {
	TechniqueID        string   `json:"technique_id"`
	Name               string   `json:"name"`
	Tactic             string   `json:"tactic"`
	ThematicDomain     string   `json:"thematic_domain"`
	MitigatingControls []string `json:"mitigating_controls"`
	RelatedCWEs        []string `json:"related_cwes"`
	Description        string   `json:"description"`
}

// AttackMapping aliases AttackTechniqueEntry for MITRE ATT&CK mapping consumers.
type AttackMapping = AttackTechniqueEntry

// LifecycleEdgeEntry represents a sovereign regulatory supersession or derivation relationship.
type LifecycleEdgeEntry struct {
	FromFramework string `json:"from_framework"`
	Predicate     string `json:"predicate"` // SUPERSEDES_FRAMEWORK or DERIVED_FROM
	ToFramework   string `json:"to_framework"`
	Jurisdiction  string `json:"jurisdiction"`
	Authority     string `json:"authority"`
	EffectiveDate string `json:"effective_date"`
	Rationale     string `json:"rationale"`
}

